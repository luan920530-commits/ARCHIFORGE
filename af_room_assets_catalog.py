ROOM_ENUM_ITEMS = tuple(ROOMS)
ASSET_ENUM_ITEMS = {
    room: tuple((record[0], record[1], record[2]) for record in assets)
    for room, assets in ROOM_ASSETS.items()
}
ASSET_LOOKUP = {
    record[0]: (room, record)
    for room, assets in ROOM_ASSETS.items()
    for record in assets
}


def assets_for_room(room):
    """Return the immutable records available for a room ID."""
    return ROOM_ASSETS.get(room, ())


def find_asset(room, asset_id):
    """Return a room asset record, or None when it is not in that room."""
    entry = ASSET_LOOKUP.get(asset_id)
    if entry is None or entry[0] != room:
        return None
    return entry[1]
